"""스키마의 단일 진실 공급원.

자식 테이블의 이름과 컬럼은 config/tab_config.json 이 이미 선언하고 있다.
db_init 이 그 목록을 손으로 한 번 더 적어두고 있었기 때문에, 탭을 하나
추가하면 두 곳을 고쳐야 했고 어긋나도 아무도 알아채지 못했다. 여기서 생성해서
그 위험을 없앤다.

구조는 아래 상수로 선언하고 PostgreSQL 렌더러(postgres_all_ddl)가 DDL 을
만든다.
"""

from genviewer.config.config import tab_config

PROCESS_TABLE = "process"
DEVICE_TABLE = "device"
CHANGE_LOG_TABLE = "change_log"


def child_tables() -> dict[str, list[str]]:
    """자식 테이블 이름 -> payload 컬럼 목록. tab_config.json 이 원본이다."""
    return {info["table"]: list(info["columns"]) for info in tab_config.values()}


# repo 가 호출자에게서 받은 테이블/컬럼 이름을 검증하는 allow-list.
TABLE_COLUMNS = child_tables()


# ---------------------------------------------------------------------------
# PostgreSQL
# ---------------------------------------------------------------------------
#
# 예전 SQLite 스키마 대비 의도적으로 조인 부분:
#
#  1. device_id 를 NOT NULL 로 하고 인덱스를 붙였다. 모든 조회가 이 컬럼으로
#     필터링하는데 지금까지 인덱스가 없었다.
#  2. payload 컬럼을 NOT NULL DEFAULT '' 로. 앱은 이미 row.get(c, "") 를 쓰고,
#     export 단계에서 None 을 "" 로 바꾸고 있었다. None/"" 이중성을 없앤다.
#  3. device 이름에 UNIQUE 를 걸지 않는다. 한동안 UNIQUE (process_id, name) 이
#     있었는데, 현장 CSV 에는 같은 CdsLibName/InstCellName 을 가진 행이 정상적으로
#     여러 개 들어온다. 그 제약 때문에 임포트가 그런 행들을 device 하나로 합쳐
#     버렸고, 사람이 같은 이름으로 device 를 추가하면 저장이 UniqueViolation 으로
#     죽었다. 이름은 식별자가 아니라 표시용 값이다 - 식별은 id 가 한다.
#     (참조하는 쪽도 전부 id 를 쓴다. name 을 가리키는 외래키는 하나도 없다.)
#  4. version / updated_at / updated_by. 낙관적 잠금(service/repo/device.py)이
#     이 컬럼들을 쓴다.

from psycopg import sql  # noqa: E402

# pg_advisory_xact_lock 의 네임스페이스. 다른 앱과 겹치지 않게 고정값을 쓴다.
ADVISORY_LOCK_CLASS = 4919

# 고정 테이블에 CREATE TABLE 을 처음 쓴 뒤 더한 컬럼. 이미 있는 DB 에는 init_db
# 재실행이 더하고(아래 DO 블록), status 는 빠진 것을 알린다(diagnostics.probe).
# 둘이 같은 목록을 보도록 여기 하나만 둔다. 새 DB 의 CREATE TABLE 에도 같은
# 자리(ADD COLUMN 이 붙이는 자리)에 있어야 새 DB 와 옮긴 DB 의 모양이 같다.
FIXED_ADDED_COLUMNS = {
    PROCESS_TABLE: ("release",),
    CHANGE_LOG_TABLE: ("process_release",),
}

# process 행 하나가 (이름, 버전) 쌍이다(phase 19). 버전 '' 은 "버전 없음" 이고 옛
# process 가 모두 이것이 된다. release 를 NULL 허용으로 두지 않는다 - PG 10~15 의
# UNIQUE 는 NULL 끼리 겹쳐도 막지 않는다.
#
# UNIQUE 는 테이블 제약 줄로 쓰고 괄호 앞에 공백을 둔다. tests/test_schema.py 가
# 본문의 줄마다 첫 낱말 뒤의 공백까지 맞춰 컬럼을 뽑는다.
_PG_PROCESS_DDL = sql.SQL("""
    CREATE TABLE IF NOT EXISTS process (
        id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name    TEXT NOT NULL,
        release TEXT NOT NULL DEFAULT '',
        UNIQUE (name, release)
    )
""")

# 이미 만들어진 DB 의 process 를 (이름, 버전) 쌍으로 옮긴다. 순서: 컬럼 → 새 제약
# → 옛 제약. 옛 UNIQUE (name) 은 이름이 아니라 컬럼으로 찾는다(손으로 만든 DB 는
# 이름이 다를 수 있다). 다 되어 있으면 ALTER 를 하나도 실행하지 않는다 - 할 일이
# 없어도 ACCESS EXCLUSIVE 를 잡기 때문이다(pg_child_add_columns_ddl 참고).
# % 를 쓰지 않는 이유와 attname 캐스트는 _PG_DEVICE_DROP_NAME_UNIQUE 와 같다.
#
# 옛 process 는 id, name 뿐이라 ADD COLUMN 이 붙이는 자리가 새 DB 의 name 바로
# 다음과 같다. PostgreSQL 10 에서는 DEFAULT 가 있는 ADD COLUMN 이 테이블을 다시
# 쓴다(11+ 는 즉시). process 는 몇 줄뿐이다.
_PG_PROCESS_MOVE_TO_RELEASE = sql.SQL("""
    -- process 에 release 를 더하고 UNIQUE 를 (name, release) 로 바꾼다
    DO $$
    DECLARE con text;
    BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_attribute
                       WHERE attrelid = 'process'::regclass
                         AND attname = 'release' AND NOT attisdropped) THEN
            ALTER TABLE process ADD COLUMN release TEXT NOT NULL DEFAULT '';
        END IF;

        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint c
            WHERE c.conrelid = 'process'::regclass AND c.contype = 'u'
              AND (SELECT array_agg(a.attname::text ORDER BY a.attname::text)
                   FROM pg_attribute a
                   WHERE a.attrelid = c.conrelid AND a.attnum = ANY(c.conkey))
                  = ARRAY['name', 'release']::text[]
        ) THEN
            ALTER TABLE process
                ADD CONSTRAINT process_name_release_key UNIQUE (name, release);
        END IF;

        FOR con IN
            SELECT c.conname FROM pg_constraint c
            WHERE c.conrelid = 'process'::regclass AND c.contype = 'u'
              AND (SELECT array_agg(a.attname::text ORDER BY a.attname::text)
                   FROM pg_attribute a
                   WHERE a.attrelid = c.conrelid AND a.attnum = ANY(c.conkey))
                  = ARRAY['name']::text[]
        LOOP
            EXECUTE 'ALTER TABLE process DROP CONSTRAINT ' || quote_ident(con);
        END LOOP;
    END $$;
""")

_PG_DEVICE_DDL = sql.SQL("""
    CREATE TABLE IF NOT EXISTS device (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        process_id  BIGINT NOT NULL REFERENCES process(id) ON DELETE CASCADE,
        name        TEXT NOT NULL,
        celltype    TEXT NOT NULL,
        description TEXT NOT NULL DEFAULT '',
        "order"     INTEGER NOT NULL DEFAULT 0,
        version     INTEGER NOT NULL DEFAULT 1,
        updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_by  TEXT NOT NULL DEFAULT ''
    )
""")

# 이미 만들어진 DB 에서 옛 UNIQUE (process_id, name) 을 떼어낸다.
#
# CREATE TABLE IF NOT EXISTS 는 이미 있는 테이블을 손대지 않으므로, 위에서 줄을
# 지우는 것만으로는 운영 중인 DB 가 바뀌지 않는다. 제약 이름을 적어 넣는 대신
# 카탈로그에서 찾는다 - 손으로 만든 DB 는 이름이 다를 수 있다.
#
# 문자열에 % 를 쓰지 않는다. psycopg 는 파라미터가 있을 때 % 를 자리표시자로 읽는데,
# format('... %I', ...) 가 들어 있으면 이 DDL 을 파라미터와 함께 쓰려는 순간 깨진다.
# quote_ident 로 붙이면 그 함정이 없다.
_PG_DEVICE_DROP_NAME_UNIQUE = sql.SQL("""
    -- device 의 옛 UNIQUE (process_id, name) 을 뗀다
    DO $$
    DECLARE con text;
    BEGIN
        FOR con IN
            SELECT c.conname FROM pg_constraint c
            WHERE c.conrelid = 'device'::regclass AND c.contype = 'u'
              -- attname 은 name 타입이다. text[] 와 그냥 비교하면
              -- "operator does not exist: name[] = text[]" 로 죽는다.
              AND (SELECT array_agg(a.attname::text ORDER BY a.attname::text)
                   FROM pg_attribute a
                   WHERE a.attrelid = c.conrelid AND a.attnum = ANY(c.conkey))
                  = ARRAY['name', 'process_id']::text[]
        LOOP
            EXECUTE 'ALTER TABLE device DROP CONSTRAINT ' || quote_ident(con);
        END LOOP;
    END $$;
""")

_PG_DEVICE_INDEXES = [
    sql.SQL("CREATE INDEX IF NOT EXISTS idx_device_process_id ON device(process_id)"),
    sql.SQL(
        'CREATE INDEX IF NOT EXISTS idx_device_process_id_order '
        'ON device(process_id, "order", id)'
    ),
]


# 변경 이력. 누가 언제 무엇을 바꿨는지를 앱이 직접 쓴다.
#
# device_id 에 외래키를 걸지 않는 것이 이 테이블의 요점이다. 걸면 device 가
# 지워질 때 그 device 의 이력이 CASCADE 로 같이 사라지는데, 사람이 가장 보고
# 싶어 하는 것이 정확히 "지워진 그것" 이다. process/device 도 id 가 아니라
# 이름 문자열로 박는다 - 원본 행이 사라져도 읽을 수 있어야 한다.
#
# 트리거가 아니라 앱이 쓴다. 이유:
#   1. 탭 저장은 행 단위 수정이 아니라 DELETE 전체 + INSERT 전체라서, 행
#      트리거를 달면 셀 하나 고친 저장이 로그 십수 줄이 된다.
#   2. 옛값은 이미 읽고 있다 (device 는 FOR UPDATE, 자식은 DELETE RETURNING).
#   3. 전원이 같은 DB role 로 붙으므로 트리거 안의 current_user 로는 사람을
#      구분할 수 없다. 어차피 앱이 이름을 실어 보내야 한다.
#
# 대가: psql 로 직접 고친 것은 남지 않는다. 앱 role 은 DML 만 가능하고 직접
# 편집은 관리자가 일부러 할 때뿐이라 받아들인다.
_PG_CHANGE_LOG_DDL = sql.SQL("""
    CREATE TABLE IF NOT EXISTS change_log (
        id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        at           TIMESTAMPTZ NOT NULL DEFAULT now(),
        actor        TEXT NOT NULL DEFAULT '',
        source       TEXT NOT NULL DEFAULT '',
        action       TEXT NOT NULL,
        process_name TEXT NOT NULL DEFAULT '',
        device_name  TEXT NOT NULL DEFAULT '',
        device_id    BIGINT,
        table_name   TEXT NOT NULL DEFAULT '',
        summary      TEXT NOT NULL DEFAULT '',
        detail       JSONB NOT NULL DEFAULT '{}'::jsonb,
        process_release TEXT NOT NULL DEFAULT ''
    )
""")
# process_release 가 마지막인 것은 옮긴 DB 에서 ADD COLUMN 이 끝에 붙이기 때문이다.
# 새 DB 와 옮긴 DB 의 컬럼 순서를 맞춘다.

_PG_CHANGE_LOG_INDEXES = [
    # 기본 조회는 "최근 것부터". id 를 같이 넣는 것은 같은 at 을 가진 행들의
    # 순서를 고정하기 위한 것이다 - --follow 가 줄을 건너뛰면 안 된다.
    sql.SQL(
        "CREATE INDEX IF NOT EXISTS idx_change_log_at "
        "ON change_log(at DESC, id DESC)"
    ),
    sql.SQL(
        "CREATE INDEX IF NOT EXISTS idx_change_log_process_at "
        "ON change_log(process_name, at DESC)"
    ),
    sql.SQL(
        "CREATE INDEX IF NOT EXISTS idx_change_log_actor_at "
        "ON change_log(actor, at DESC)"
    ),
]


def pg_child_ddl(table: str, columns: list[str]) -> sql.Composed:
    payload = sql.SQL(",\n        ").join(
        sql.SQL("{} TEXT NOT NULL DEFAULT ''").format(sql.Identifier(c)) for c in columns
    )
    return sql.SQL(
        "CREATE TABLE IF NOT EXISTS {tbl} (\n"
        "        id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n"
        "        device_id BIGINT NOT NULL REFERENCES device(id) ON DELETE CASCADE,\n"
        "        {cols}\n"
        "    )"
    ).format(tbl=sql.Identifier(table), cols=payload)


def pg_child_index_ddl(table: str) -> sql.Composed:
    # (device_id, id): 조회가 device_id 로 필터링하고 id 로 정렬한다.
    return sql.SQL("CREATE INDEX IF NOT EXISTS {ix} ON {tbl}(device_id, id)").format(
        ix=sql.Identifier(f"idx_{table}_device_id"), tbl=sql.Identifier(table)
    )


def pg_child_add_columns_ddl(table: str, columns: list[str]) -> sql.Composed:
    """이미 있는 탭 테이블에 tab_config 에서 늘어난 컬럼을 더한다.

    CREATE TABLE IF NOT EXISTS 는 있는 테이블을 손대지 않으므로, 기존 탭에 컬럼을
    더하면 운영 DB 에는 그 컬럼이 없어 저장·불러오기가 42703 으로 죽는다.

    ADD COLUMN IF NOT EXISTS 를 그냥 실행하지 않는다. 컬럼이 이미 있어도 ACCESS
    EXCLUSIVE 를 먼저 잡아서, 쓰는 중에 init_db 를 다시 돌리면 읽는 트랜잭션 뒤에서
    기다리는 동안 그 탭을 읽는 모든 사람이 줄을 선다. 카탈로그를 보고 빠진
    컬럼만 ALTER 한다.

    regclass 로 찾는 이유: ALTER TABLE 과 같은 search_path 규칙으로 같은 테이블을
    가리킨다. quote_ident 는 이름의 대소문자를 그대로 둔다. % 를 쓰지 않는 이유는
    _PG_DEVICE_DROP_NAME_UNIQUE 와 같다. attname(name) 은 따옴표 리터럴과 비교하므로
    name 으로 맞춰진다.

    PostgreSQL 10 에서는 DEFAULT 가 있는 ADD COLUMN 이 테이블을 다시 쓴다(11+ 는
    즉시). 운영은 15 다.
    """
    checks = sql.SQL("\n").join(
        sql.SQL(
            "        IF NOT EXISTS (SELECT 1 FROM pg_attribute\n"
            "                       WHERE attrelid = quote_ident({tbl_name})::regclass\n"
            "                         AND attname = {col_name} AND NOT attisdropped) THEN\n"
            "            ALTER TABLE {tbl} ADD COLUMN IF NOT EXISTS {col}"
            " TEXT NOT NULL DEFAULT '';\n"
            "        END IF;"
        ).format(
            tbl_name=sql.Literal(table),
            col_name=sql.Literal(c),
            tbl=sql.Identifier(table),
            col=sql.Identifier(c),
        )
        for c in columns
    )
    return sql.SQL(
        "-- {tbl} 에 빠진 컬럼을 더한다\n"
        "    DO $$\n"
        "    BEGIN\n"
        "{checks}\n"
        "    END $$"
    ).format(tbl=sql.Identifier(table), checks=checks)


def postgres_all_ddl() -> list:
    out = [
        _PG_PROCESS_DDL,
        _PG_PROCESS_MOVE_TO_RELEASE,
        _PG_DEVICE_DDL,
        _PG_DEVICE_DROP_NAME_UNIQUE,
        *_PG_DEVICE_INDEXES,
        _PG_CHANGE_LOG_DDL,
        # 탭 테이블과 같은 방식(카탈로그를 보고 빠진 것만)으로 더한다. 라벨은
        # "change_log" 라 탭 테이블의 것과 겹치지 않는다.
        pg_child_add_columns_ddl(
            CHANGE_LOG_TABLE, list(FIXED_ADDED_COLUMNS[CHANGE_LOG_TABLE])
        ),
        *_PG_CHANGE_LOG_INDEXES,
    ]
    for table, columns in child_tables().items():
        out.append(pg_child_ddl(table, columns))
        out.append(pg_child_index_ddl(table))
        out.append(pg_child_add_columns_ddl(table, columns))
    return out
