# PostgreSQL
# ---------------------------------------------------------------------------
#
# SQLite 스키마 대비 의도적으로 조인 부분:
#
#  1. device_id 를 NOT NULL 로 하고 인덱스를 붙였다. 모든 조회가 이 컬럼으로
#     필터링하는데 지금까지 인덱스가 없었다.
#  2. payload 컬럼을 NOT NULL DEFAULT '' 로. 앱은 이미 row.get(c, "") 를 쓰고,
#     export 단계에서 None 을 "" 로 바꾸고 있었다. None/"" 이중성을 없앤다.
#  3. UNIQUE (process_id, name). InstCellName 은 CdsLibName 안에서의 식별자이고,
#     두 사용자가 동시에 같은 device 를 만드는 것을 DB 가 막아준다.
#  4. version / updated_at / updated_by. 컬럼은 여기서 한 번에 만들고, 이것을
#     사용하는 낙관적 잠금 로직은 다음 단계에서 붙인다. 데이터가 아직 없으므로
#     나중에 ALTER TABLE 하는 것보다 지금 넣는 편이 단순하다.

from psycopg import sql  # noqa: E402

# pg_advisory_xact_lock 의 네임스페이스. 다른 앱과 겹치지 않게 고정값을 쓴다.
ADVISORY_LOCK_CLASS = 4919

_PG_PROCESS_DDL = sql.SQL("""
    CREATE TABLE IF NOT EXISTS process (
        id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE
    )
""")

_PG_DEVICE_DDL = sql.SQL("""
    CREATE TABLE IF NOT EXISTS device (
        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        process_id  BIGINT NOT NULL REFERENCES process(id) ON DELETE CASCADE,
        name        TEXT NOT NULL,
        celltype    TEXT NOT NULL,
        description TEXT NOT NULL DEFAULT '',
        "order"     INTEGER NOT NULL DEFAULT 0,
        version     INTEGER NOT NULL DEFAULT 1,
        updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_by  TEXT NOT NULL DEFAULT '',
        UNIQUE (process_id, name)
    )
""")

_PG_DEVICE_INDEXES = [
    sql.SQL("CREATE INDEX IF NOT EXISTS idx_device_process_id ON device(process_id)"),
    sql.SQL(
        'CREATE INDEX IF NOT EXISTS idx_device_process_id_order '
        'ON device(process_id, "order", id)'
    ),
]


def pg_child_ddl(table: str, columns: list[str]) -> sql.Composed:
    payload = sql.SQL(",\n        ").join(
        sql.SQL("{} TEXT NOT NULL DEFAULT ''").format(sql.Identifier(c)) for c in columns
    )
    return sql.SQL(
        "CREATE TABLE IF NOT EXISTS {tbl} (\n"
        "        id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n"
        "        device_id BIGINT NOT NULL REFERENCES device(id) ON DELETE CASCADE,\n"
        "        {cols}\n"
        "    )"
    ).format(tbl=sql.Identifier(table), cols=payload)


def pg_child_index_ddl(table: str) -> sql.Composed:
    # (device_id, id): 조회가 device_id 로 필터링하고 id 로 정렬한다.
    return sql.SQL("CREATE INDEX IF NOT EXISTS {ix} ON {tbl}(device_id, id)").format(
        ix=sql.Identifier(f"idx_{table}_device_id"), tbl=sql.Identifier(table)
    )


def postgres_all_ddl() -> list:
    out = [_PG_PROCESS_DDL, _PG_DEVICE_DDL, *_PG_DEVICE_INDEXES]
    for table, columns in child_tables().items():
        out.append(pg_child_ddl(table, columns))
        out.append(pg_child_index_ddl(table))
    return out
